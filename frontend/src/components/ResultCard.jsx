import React from 'react';
import {
  ShieldCheck,
  ShieldAlert,
  AlertTriangle,
  CheckCircle,
  Clock,
  Layers,
  ChevronDown,
  Terminal,
  ExternalLink
} from 'lucide-react';

export default function ResultCard({ result, onScrollToFeatures }) {
  if (!result) return null;

  const isPhishing = result.prediction.toLowerCase() === 'phishing';

  // Risk level colors & styling
  const getRiskConfig = (level) => {
    switch (level?.toLowerCase()) {
      case 'low':
        return { color: '#10b981', bg: 'rgba(16, 185, 129, 0.1)', border: 'rgba(16, 185, 129, 0.3)' };
      case 'moderate':
        return { color: '#f59e0b', bg: 'rgba(245, 158, 11, 0.1)', border: 'rgba(245, 158, 11, 0.3)' };
      case 'high':
        return { color: '#f97316', bg: 'rgba(249, 115, 22, 0.1)', border: 'rgba(249, 115, 22, 0.3)' };
      case 'critical':
      default:
        return { color: '#ef4444', bg: 'rgba(239, 68, 68, 0.1)', border: 'rgba(239, 68, 68, 0.3)' };
    }
  };

  const riskConfig = getRiskConfig(result.risk_level);

  return (
    <div
      className="glass-card"
      style={{
        padding: '2rem',
        marginBottom: '2rem',
        borderLeft: `4px solid ${isPhishing ? '#ef4444' : '#10b981'}`,
        boxShadow: `0 8px 30px ${isPhishing ? 'rgba(239, 68, 68, 0.15)' : 'rgba(16, 185, 129, 0.15)'}`
      }}
    >
      {/* Top Banner: Status + Risk Level */}
      <div style={{
        display: 'flex',
        flexWrap: 'wrap',
        alignItems: 'center',
        justifyContent: 'space-between',
        gap: '1rem',
        borderBottom: '1px solid rgba(255, 255, 255, 0.08)',
        paddingBottom: '1.25rem',
        marginBottom: '1.5rem'
      }}>
        <div style={{ display: 'flex', alignItems: 'center', gap: '1rem' }}>
          <div style={{
            width: '52px',
            height: '52px',
            borderRadius: '12px',
            display: 'flex',
            alignItems: 'center',
            justifyContent: 'center',
            background: isPhishing ? 'rgba(239, 68, 68, 0.15)' : 'rgba(16, 185, 129, 0.15)',
            border: `1px solid ${isPhishing ? 'rgba(239, 68, 68, 0.3)' : 'rgba(16, 185, 129, 0.3)'}`
          }}>
            {isPhishing ? (
              <ShieldAlert size={30} color="#ef4444" />
            ) : (
              <ShieldCheck size={30} color="#10b981" />
            )}
          </div>
          <div>
            <div style={{ display: 'flex', alignItems: 'center', gap: '0.65rem' }}>
              <h2 style={{ fontSize: '1.65rem', fontWeight: 800, letterSpacing: '-0.02em' }}>
                {result.prediction}
              </h2>
              <span className={`badge ${isPhishing ? 'badge-danger' : 'badge-safe'}`}>
                {isPhishing ? 'Malicious Risk' : 'Legitimate URL'}
              </span>
            </div>
            <div style={{ fontSize: '0.85rem', color: 'var(--text-dim)', marginTop: '2px' }}>
              Verdict generated by Random Forest Classifier (30-Feature Inspection)
            </div>
          </div>
        </div>

        <div style={{ display: 'flex', alignItems: 'center', gap: '1.25rem' }}>
          {/* Risk Level Badge */}
          <div style={{ textAlign: 'right' }}>
            <div style={{ fontSize: '0.75rem', color: 'var(--text-dim)', textTransform: 'uppercase' }}>
              Risk Classification
            </div>
            <div style={{
              fontSize: '1.1rem',
              fontWeight: 700,
              color: riskConfig.color
            }}>
              {result.risk_level} Risk ({result.risk_score}/100)
            </div>
          </div>

          {/* Confidence */}
          <div style={{
            background: 'rgba(255, 255, 255, 0.05)',
            padding: '0.5rem 1rem',
            borderRadius: '10px',
            border: '1px solid var(--border-subtle)',
            textAlign: 'center'
          }}>
            <div style={{ fontSize: '0.7rem', color: 'var(--text-dim)', textTransform: 'uppercase' }}>
              Confidence
            </div>
            <div style={{ fontSize: '1.2rem', fontWeight: 700, color: 'var(--accent-cyan)' }}>
              {(result.confidence * 100).toFixed(1)}%
            </div>
          </div>
        </div>
      </div>

      {/* Target URL Display */}
      <div style={{
        background: '#070b13',
        padding: '0.75rem 1rem',
        borderRadius: '8px',
        border: '1px solid rgba(255, 255, 255, 0.06)',
        marginBottom: '1.25rem',
        display: 'flex',
        alignItems: 'center',
        gap: '0.75rem',
        fontFamily: 'var(--font-mono)',
        fontSize: '0.9rem',
        color: '#e2e8f0',
        wordBreak: 'break-all'
      }}>
        <Terminal size={16} color="var(--accent-cyan)" style={{ flexShrink: 0 }} />
        <span style={{ color: 'var(--text-dim)', userSelect: 'none' }}>TARGET:</span>
        <span>{result.url}</span>
      </div>

      {/* Risk Score Progress Bar */}
      <div style={{ marginBottom: '1.5rem' }}>
        <div style={{ display: 'flex', justifyContent: 'space-between', fontSize: '0.8rem', color: 'var(--text-dim)', marginBottom: '0.35rem' }}>
          <span>Risk Probability Spectrum</span>
          <span>{result.risk_score}% Phishing Probability</span>
        </div>
        <div style={{
          width: '100%',
          height: '8px',
          background: 'rgba(255, 255, 255, 0.08)',
          borderRadius: '999px',
          overflow: 'hidden'
        }}>
          <div style={{
            width: `${Math.max(result.risk_score, 2)}%`,
            height: '100%',
            background: isPhishing
              ? 'linear-gradient(90deg, #f59e0b, #ef4444)'
              : 'linear-gradient(90deg, #10b981, #06b6d4)',
            transition: 'width 0.8s cubic-bezier(0.4, 0, 0.2, 1)'
          }}></div>
        </div>
      </div>

      {/* Diagnostic Message */}
      <div style={{
        background: riskConfig.bg,
        border: `1px solid ${riskConfig.border}`,
        borderRadius: '10px',
        padding: '1rem',
        marginBottom: '1.5rem',
        color: 'var(--text-main)',
        fontSize: '0.95rem',
        lineHeight: 1.5
      }}>
        <strong>Evaluation Summary:</strong> {result.message}
      </div>

      {/* Detected Risk Flags & Positive Signals */}
      <div className="grid-cols-2" style={{ marginBottom: '1.5rem' }}>
        {/* Risk Flags */}
        <div style={{
          background: 'rgba(239, 68, 68, 0.04)',
          border: '1px solid rgba(239, 68, 68, 0.15)',
          borderRadius: '10px',
          padding: '1.25rem'
        }}>
          <div style={{
            display: 'flex',
            alignItems: 'center',
            gap: '0.5rem',
            color: '#ef4444',
            fontWeight: 600,
            fontSize: '0.95rem',
            marginBottom: '0.75rem'
          }}>
            <AlertTriangle size={18} />
            <span>Identified Threat Signals ({result.detected_risk_flags?.length || 0})</span>
          </div>
          {result.detected_risk_flags?.length > 0 ? (
            <ul style={{ listStyle: 'none', padding: 0, margin: 0, display: 'flex', flexDirection: 'column', gap: '0.5rem' }}>
              {result.detected_risk_flags.map((flag, idx) => (
                <li key={idx} style={{
                  fontSize: '0.85rem',
                  color: '#fca5a5',
                  display: 'flex',
                  alignItems: 'flex-start',
                  gap: '0.5rem'
                }}>
                  <span style={{ color: '#ef4444', marginTop: '2px' }}>•</span>
                  <span>{flag}</span>
                </li>
              ))}
            </ul>
          ) : (
            <div style={{ fontSize: '0.85rem', color: 'var(--text-dim)', fontStyle: 'italic' }}>
              No critical phishing anomaly triggers detected.
            </div>
          )}
        </div>

        {/* Positive Safety Signals */}
        <div style={{
          background: 'rgba(16, 185, 129, 0.04)',
          border: '1px solid rgba(16, 185, 129, 0.15)',
          borderRadius: '10px',
          padding: '1.25rem'
        }}>
          <div style={{
            display: 'flex',
            alignItems: 'center',
            gap: '0.5rem',
            color: '#10b981',
            fontWeight: 600,
            fontSize: '0.95rem',
            marginBottom: '0.75rem'
          }}>
            <CheckCircle size={18} />
            <span>Safety Indicators ({result.positive_safety_indicators?.length || 0})</span>
          </div>
          {result.positive_safety_indicators?.length > 0 ? (
            <ul style={{ listStyle: 'none', padding: 0, margin: 0, display: 'flex', flexDirection: 'column', gap: '0.5rem' }}>
              {result.positive_safety_indicators.map((ind, idx) => (
                <li key={idx} style={{
                  fontSize: '0.85rem',
                  color: '#86efac',
                  display: 'flex',
                  alignItems: 'flex-start',
                  gap: '0.5rem'
                }}>
                  <span style={{ color: '#10b981', marginTop: '2px' }}>✓</span>
                  <span>{ind}</span>
                </li>
              ))}
            </ul>
          ) : (
            <div style={{ fontSize: '0.85rem', color: 'var(--text-dim)', fontStyle: 'italic' }}>
              No positive TLS/domain safety signals confirmed.
            </div>
          )}
        </div>
      </div>

      {/* Footer bar */}
      <div style={{
        display: 'flex',
        flexWrap: 'wrap',
        alignItems: 'center',
        justifyContent: 'space-between',
        fontSize: '0.75rem',
        color: 'var(--text-dim)',
        paddingTop: '0.75rem',
        borderTop: '1px solid rgba(255, 255, 255, 0.06)'
      }}>
        <div style={{ display: 'flex', alignItems: 'center', gap: '0.35rem' }}>
          <Clock size={14} />
          <span>Analyzed: {new Date(result.analysis_timestamp).toLocaleString()}</span>
        </div>
        <button
          onClick={onScrollToFeatures}
          className="btn btn-secondary"
          style={{ padding: '0.4rem 0.85rem', fontSize: '0.8rem' }}
        >
          <Layers size={14} />
          <span>View 30 Extracted Feature Values</span>
        </button>
      </div>
    </div>
  );
}
